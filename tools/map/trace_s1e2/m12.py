import sys; sys.path.insert(0,'/home/claude/tools'); from paint import G, poly_g
g=G()
# 청문회 전실 (TOP): 위쪽 벽 · 테이블
g.hx(10,0,1); g.vy(10,0,1); g.vy(1,0,9); g.hx(1,0,9)   # 위쪽 두 변 유리창 벽 두께
g.r('C',4,6,6,7); g.c('X',(5,6)); g.c('C',(4,6),(6,6),(4,7),(5,7),(6,7))
# 대기실 4개 (문: 복도 쪽)
def room(x0,y0,x1,y1,door):
    for x in range(x0,x1+1):
        g.c('#',(x,y0),(x,y1))
    for y in range(y0,y1+1):
        g.c('#',(x0,y),(x1,y))
    for c in door: g.o(c)
    g.c('C',(x0+2,y0+2),(x0+2,y0+3),(x0+3,y0+2))
room(5,11,10,17,[(10,13),(10,14)])     # 왼쪽 위
