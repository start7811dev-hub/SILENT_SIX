import numpy as np,g
from PIL import Image,ImageDraw,ImageFont
Hi=np.linalg.inv(np.array(g.H).reshape(3,3))
O=[(1500,0),(2900,500),(0,900),(1300,800),(2700,1300),(1000,1700),(2100,1900)]
def hgt(sx):return 48+max(0,(1500-sx))*17/1300.0
def inv(sx,sy):
    v=Hi@np.array([sx,sy,1.0]);return v[0]/v[2],v[1]/v[2]
def top2g(c,p):   # crop px on slab centre -> ground grid coords
    sx=(O[c][0]+p[0])/3.0;sy=(O[c][1]+p[1])/3.0;return inv(sx,sy+hgt(sx))
def gnd(c,p):
    return inv((O[c][0]+p[0])/3.0,(O[c][1]+p[1])/3.0)
