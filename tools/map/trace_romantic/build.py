class G:
    def __init__(s, W, Hh=None, border='#', fill='.'):
        s.W = W; s.Hh = Hh or W; s.g = [[fill] * s.W for _ in range(s.Hh)]
        if border:
            for i in range(s.W): s.g[0][i] = s.g[s.Hh - 1][i] = border
            for j in range(s.Hh): s.g[j][0] = s.g[j][s.W - 1] = border
    def R(s, x0, x1, y0, y1, c='#'):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if 0 <= x < s.W and 0 <= y < s.Hh: s.g[y][x] = c
        return s
    def O(s, x0, x1, y0, y1, c='#'):   # 테두리만
        for x in range(x0, x1 + 1): s.P(c, (x, y0), (x, y1))
        for y in range(y0, y1 + 1): s.P(c, (x0, y), (x1, y))
        return s
    def P(s, c, *pts):
        for x, y in pts:
            if 0 <= x < s.W and 0 <= y < s.Hh: s.g[y][x] = c
        return s
    def rows(s): return [''.join(r) for r in s.g]
    # ---- 그림 좌표(px)로 지정: 벽 윗면 기준이면 h=벽 높이(px), 바닥 기준이면 h=0 ----
    def proj(s, pts, h=40, src=None):
        import numpy as np
        s.pr = lib.ProjH(s.W, s.Hh, src, pts) if src else lib.Proj(s.W, s.Hh, *pts); s.HI = np.linalg.inv(s.pr.H); s.h = h; return s
    def g2(s, px, py, h=None):
        import numpy as np
        v = s.HI @ np.array([px, py + (s.h if h is None else h), 1.0]); return (v[0] / v[2], v[1] / v[2])
    def WL(s, pts, c='#', h=None, gaps=()):
        '''px 꺾은선을 따라 칸을 채운다(벽). gaps: 비울 칸 목록.'''
        for (a, b) in zip(pts, pts[1:]):
            x0, y0 = s.g2(a[0], a[1], h); x1, y1 = s.g2(b[0], b[1], h)
            n = int(max(abs(x1 - x0), abs(y1 - y0)) * 4) + 1
            for i in range(n + 1):
                x = x0 + (x1 - x0) * i / n; y = y0 + (y1 - y0) * i / n; s.P(c, (int(x), int(y)))
        s.P('.', *gaps); return s
    def FP(s, poly, c='B', h=None, thr=0.5):
        '''px 다각형(윗면) 안에 중심이 드는 칸을 채운다.'''
        from PIL import Image as I2, ImageDraw as D2
        gp = [s.g2(p[0], p[1], h) for p in poly]; S = 8
        im = I2.new('L', (s.W * S, s.Hh * S), 0); D2.Draw(im).polygon([(x * S, y * S) for x, y in gp], fill=255); a = im.load()
        for y in range(s.Hh):
            for x in range(s.W):
                n = sum(1 for j in range(S) for i in range(S) if a[x * S + i, y * S + j]) / (S * S)
                if n >= thr: s.g[y][x] = c
        return s
COL = {'#': (255, 60, 60), 'B': (255, 0, 255), 'C': (255, 170, 0), 'W': (255, 255, 0), 'V': (0, 160, 255), 'X': (0, 255, 120), 'K': (255, 0, 255), 'T': (255, 0, 255), 'H': (180, 120, 255), 'J': (255, 120, 60), 'L': (120, 255, 255)}
M = {}
def reg(k, W, pts, h, g, hts=None, Hh=None, **kw):
    M[k] = dict(W=W, Hh=Hh or W, pts=pts, h=h, MAP=g.rows(), hts=hts or {}, **kw)
def PR(m):
    return lib.ProjH(m['W'], m['Hh'], m['src'], m['pts']) if m.get('src') else lib.Proj(m['W'], m['Hh'], *m['pts'])

def check(k, extra=None, out=None, marks=None):
    m = M[k]; pr = PR(m)
    im = Image.open(os.path.join(lib.SRC, 'bgp_%s_%s.jpg' % (k[:-1], k[-1]))).convert('RGBA')
    ov = Image.new('RGBA', im.size, (0, 0, 0, 0)); d = ImageDraw.Draw(ov); MAP = m['MAP']
    for y in range(m['Hh']):
        for x in range(m['W']):
            c = MAP[y][x]
            if c == '.': continue
            cc = COL.get(c, (255, 60, 60)); q = [pr.P(x, y), pr.P(x + 1, y), pr.P(x + 1, y + 1), pr.P(x, y + 1)]
            hh = m['hts'].get(c, m['h'] if c in '#BWKTH' else 12 if c in 'CJ' else 0)
            d.polygon(q, fill=cc + (55,), outline=cc + (150,))
            if hh: d.polygon([(a, b - hh) for a, b in q], outline=cc + (255,))
    f = lib.font(10)
    for i in range(0, m['W'], 2):
        p = pr.P(i + .5, m['Hh'] + .7); d.text((p[0] - 5, p[1] - 5), str(i), fill=(255, 255, 255, 255), font=f)
