def check(n):
    o=OUT[n];M=o['MAP'];c,r=len(M[0]),len(M);seen=set();st=[o['start'][0]]
    while st:
        x,y=st.pop()
        if (x,y) in seen or not(0<=x<c and 0<=y<r) or M[y][x]!='.':continue
        seen.add((x,y));st+=[(x+1,y),(x-1,y),(x,y+1),(x,y-1)]
    tot=sum(row.count('.') for row in M)
    return o['use'] in seen,len(seen),tot,all(s in seen for s in o['start'])
